import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(root, "src");
const unicodeMap = JSON.parse(await readFile(path.join(root, "node_modules", "@fontsource", "noto-serif-sc", "unicode.json"), "utf8"));

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) return sourceFiles(target);
    return /\.(ts|tsx)$/.test(entry.name) ? [target] : [];
  }));
  return nested.flat();
}

function rangeContains(range, codePoint) {
  const match = range.match(/^U\+([0-9A-F]+)(?:-([0-9A-F]+))?$/i);
  if (!match) return false;
  const start = Number.parseInt(match[1], 16);
  const end = Number.parseInt(match[2] ?? match[1], 16);
  return codePoint >= start && codePoint <= end;
}

const files = await sourceFiles(sourceRoot);
const source = (await Promise.all(files.map((file) => readFile(file, "utf8")))).join("\n");
const chineseCodePoints = new Set([...source]
  .map((character) => character.codePointAt(0))
  .filter((codePoint) => codePoint >= 0x3400 && codePoint <= 0x9fff));
const chunks = Object.entries(unicodeMap).filter(([, value]) => value
  .split(",")
  .some((range) => [...chineseCodePoints].some((codePoint) => rangeContains(range, codePoint))));

const blocks = [
  "/* Generated by scripts/build-font-css.mjs. Do not edit by hand. */",
  "@font-face {",
  "  font-family: \"Inter Variable\";",
  "  font-style: normal;",
  "  font-display: swap;",
  "  font-weight: 100 900;",
  "  src: url(../node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2) format(\"woff2-variations\");",
  "  unicode-range: U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD;",
  "}"
];

for (const [key, unicodeRange] of chunks) {
  const chunk = key.slice(1, -1);
  blocks.push(
    "",
    `/* Noto Serif SC chunk ${chunk} */`,
    "@font-face {",
    "  font-family: \"Noto Serif SC\";",
    "  font-style: normal;",
    "  font-display: swap;",
    "  font-weight: 600;",
    `  src: url(../node_modules/@fontsource/noto-serif-sc/files/noto-serif-sc-${chunk}-600-normal.woff2) format(\"woff2\");`,
    `  unicode-range: ${unicodeRange};`,
    "}"
  );
}

await writeFile(path.join(sourceRoot, "generated-fonts.css"), `${blocks.join("\n")}\n`, "utf8");
console.log(`Generated ${chunks.length} Noto Serif SC chunks for ${chineseCodePoints.size} Chinese glyphs.`);
